这种紧很日常。一句消息发出去之前，你改了三次语气。一次作品放出去之后，你刷新的不是内容，是别人的反应。反应好，你想再做一点更像那次的。反应冷，你怀疑整件事是不是不该存在。怀疑若是因为事情本身没做对，那是手艺。怀疑若只跟着冷热走，那是你把步子交给了别人的脸。

《庄子·逍遥游》写到宋荣子，有一段很克制的话。通行本是：「且举世而誉之，而不加劝，举世而非之，而不加沮，定乎内外之分，辩乎荣辱之境，斯已矣。」有的本子「境」作「竟」，竟是边界。意思在这里是清楚的：全世界称赞他，他并不因此更起劲；全世界非议他，他并不因此更沮丧。他分得清内外，也分得清荣辱的边界。庄子紧接着说，这样的人已经难得，可「虽然，犹有未树也」。未树，是还没有立起来的东西。文本没有把不受评价摆成最高的逍遥。它只是把这一步从「小知」里拔出来，又不肯让你停在一种新的得意上。

