AI 把「可欲」的目录做得又长又温柔。它不吼你，它建议你。建议的句子很完整，完整到像已经替你生活过一遍。你若照着去补，补完仍有下一句建议。建议没有恶意。它只是不知道你的腹在哪里。腹不在模型里，在你今晚用不用得上、用完会不会更像自己。更像自己，比更像一张别人的清单更接近自由。自由不是拥有的反面。自由是你还认得，哪一件是你的，哪一件只是被递到眼前。

也有人把知足听成认命。认命是觉得自己不配再要任何东西。知足不是这个。知足的人仍可以要那口热饭，仍可以要把那一页写完，仍可以要一个更适合自己的安排。他只是不再用「还不够」来否定已经在手里的生活。已经在手里的生活若被不断地否定，自由就没有地方坐。自由需要一个坐得下的现在。现在若永远只是去往更好版本的候车室，人就只是在等，等的时候还觉得自己落后。

