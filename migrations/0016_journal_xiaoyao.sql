未树也值得留着。人很容易把「我不在乎别人怎么看」说成一种新的荣。这种荣一样会加减你。你开始表演不在乎，表演到连该听的一句也拒掉。该听的一句往往不热闹。它不是举世，它是一个具体的人告诉你：这里我没用上。没用上，是事情。举世的喜欢或讨厌，是气候。气候要知道，不必把步子交给气候。庄子说宋荣子犹有未树，是在防止你把不受评价当成终点，然后在终点上骄傲。骄傲也是一种被自己的姿态困住。

评价还会从很近的人来。家里的一句「你这样不像样」，同行的一句「你这样不够专业」，都比陌生的点赞更重。重，是因为你在乎这些人。在乎可以留下。留下在乎，和被在乎决定，不是同一件事。你可以听见父亲的担心，仍把今晚的一页写完。你可以听见同行的标准，仍不肯把一句真实的话改成行话。逍遥不是翻脸。翻脸往往还在和评价打架。不打架的时候，评价经过你，像风经过树，树还在原来的地方。

列子在同一段里被拿来作对照。他御风而行，看起来已经很轻，可仍「有所待」。有所待，是还要靠一个条件。评价也可以是风。你靠好评才走得动，靠没有差评才敢发布，那就是待。待着的逍遥，风一停就掉下来。掉下来的人会更急着找下一阵风。宋荣子至少不靠那阵风加减自己。庄子说他还未树，是提醒：不靠风，只是开始，不是你可以拿来炫耀的完成。炫耀不靠风，本身又成了风。

也有评价是你欠别人的。你答应了的事没做，对方失望，那不是「举世非之」，那是你的内和外碰到了一起。把所有不舒服都叫成别人的看法，是另一种困。困在自我原谅里，并不逍遥。分得清，才用得上这段古文。分不清，宋荣子会变成一块挡箭牌。挡箭牌上写着我不在乎，后面却是不想看自己没做的部分。

