关系里的自由，最容易在亲近的人面前失败。陌生人你反倒敢说不。亲人一句失望，你就把整晚交出去，并且觉得这才是爱。爱若等于交出去，不可劫就先在家里死掉。死掉以后，你会对家里人又近又怨。怨是被劫之后的味道。味道出来时，不要只怪他们。也看看自己是不是把亲理解成了不许有自己的时辰。时辰可以很小。小的时辰若永远让得出去，连接就变成单行道。单行道上的人迟早要逃。逃的那天，看起来像突然变冷。其实冷是长期没有不可迫。

《礼记》把礼放在人与人之间，是相信人要一起生活，而一起生活需要形式，否则只剩力大的人说了算。形式可以很旧，旧到你不必全盘照用。旧形式里这一句仍然新：可以亲近，不可以挟持。挟持有时是大喊，有时是沉默施压，有时是一句我们是自己人。自己人若不能说不，就只是自己人这三个字的人质。不当人质，也不当消失的人，连接才配得上自由这个词。

连接里的自由，也要允许别人不可劫你，同样允许你不可劫别人。只要求自己被放过、却不许对方说不，是另一种迫。迫的人会觉得自己在维护关系。维护到对方不能呼吸，关系就只剩你的需要。需要是真的。真的需要若只能靠按住别人来满足，满足完仍空，因为你得到的不是一个人，是一个不能走的功能。功能会坏。人若还能走、也还愿意来，那个来才算数。算数的来，是礼还在的证据：往来，而不是拘押。

人与人之间的逍遥，最后不是各自飘走。飘走很像自由，飘完你发现自己没有地方把一句真话放下。放下真话需要一个可亲的人。可亲的人若同时又不可迫，真话才放得下，因为你知道放下以后还能走，走了以后还能回来。回来不是认输。回来是往来。往来的关系里，自由不是距离的最大值，而是挟持的最小值。最小值很难，因为它要求你在很近的地方仍不按住别人，也不允许别人按住你。近处的不按住，比远处的不相干难得多。难的那一点，才是礼还值得被今天的人重读的原因。

