内外之分，是这句话里最有用的两个字。外是别人的誉和毁，内是你自己知道的那一点：这件事你做的时候清不清，做完还认不认得。内外搅在一起的时候，一句夸奖会变成你的方向，一句皱眉会变成你的判决。方向和判决如果都从外面来，你看起来很在意别人，其实是没有自己的下一步。逍遥在这里不是去深山。深山里如果还带着那面随时等评价的镜子，山也是窄的。

不妨设想一个具体的晚上。你把一段自己的话给一个认识的人看。他回：挺好，不过如果再温和一点，会有更多人喜欢。更多人喜欢，是一个很亮的外。你几乎要改。改之前若问一句内：温和是这句话本来的意思，还是为了躲开不喜欢。若是前者，改的是清楚。若是后者，改的是你自己。宋荣子的「不加劝、不加沮」不是拒绝修改。修改可以来自事情。它拒绝的是修改来自举世的温度。

第二天若有人说好，危险会换一张脸。你好会想把下一句写得更像上一句。更像，是誉在加劝。加劝看起来像顺着自己的天赋，其实是顺着刚发生的那阵暖和。暖和会过去。过去以后，你若只记得被喜欢的样子，不记得自己当时要说的事，下一步就还是外。宋荣子的难，不是在被骂时站住。被骂时站住，人还有一股劲。难的是在被夸时也不把步子加码。不加码，夸奖才只是天气，不是方向。

还有一种评价来得很慢，慢到像你自己的声音。你反复想象某个你敬重的人会怎么看。他并没有开口。开口的是你替他准备的那一版。这一版往往比真实的他更严。你用一个虚构的标准改自己，改到连身边真正在场的人都认不出。认不出的时候，你还觉得自己在追求高。高如果没有内，只是另一座举世。庄子把内外分开，是为了让你还有一个不被代理的自己。代理的自己很勤奋，勤奋地活成别人的眼光。

AI 最会调节温度。你把一段话交给它，说「帮我改得更得体」，它会把棱角收掉，把对象扩大，把你写成一个谁都不反对的人。谁都不反对的人很安全，也很不好找。找你的人需要看见你站在哪里。站处一被磨平，评价也许变好，你却更不逍遥，因为下一步只能继续追那个更平滑的版本。你可以反过来用它：请它标出，哪些句子是在躲评价，哪些句子是事情本身需要的。标完，删不删仍由你。由你，是内外之分还在。

