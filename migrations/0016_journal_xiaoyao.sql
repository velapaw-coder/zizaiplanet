古人说的不知足，不是现代人口中那种上进心的反义词。上进可以是把一件事做深。不知足常常是把标准交出去，交给下一件可欲的东西。交出去的人看起来很忙，也很不自由。忙是因为缺口永远刷新。不自由是因为刷新的节奏不在你手里。你甚至会不好意思停。停一下，就像承认自己没有追求。追求若只是不敢停，它就不再是你的方向，而是一种不敢被看见落在后面的恐惧。

