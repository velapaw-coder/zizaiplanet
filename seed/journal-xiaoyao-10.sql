《礼记·儒行》记孔子回答鲁哀公：「儒有可亲而不可劫也，可近而不可迫也，可杀而不可辱也。」亲是可以亲近，劫是被挟持。近是可以走近，迫是被逼紧。这是在说儒者的刚毅，不是一篇现代的边界课。古人没有用「个人自由」来写它。先把原文放回它的硬度：关系可以很近，近到不能成为挟持。

只有亲、没有不可劫，人会在关系里消失。只有不可劫、没有可亲，人会安全，也会干。干的安全不是这篇的方向。同一篇还说儒者近人。主动走近，和被劫住，方向相反。

